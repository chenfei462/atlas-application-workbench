// Non-Git evidence mode: compare a baseline hash manifest against a freshly
// computed final manifest and emit FINAL_HASHES.json, FINAL_FILE_TREE.txt and
// FILE_CHANGE_REPORT.md with ADDED / MODIFIED / REMOVED / UNCHANGED.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(import.meta.dirname, '..');
const args = process.argv.slice(2);
const argValue = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : fallback;
};
const baselinePath = path.resolve(argValue('--baseline', path.join(root, 'deliverables/atlas-production/baseline/BASELINE_HASHES.json')));
const outDir = path.resolve(argValue('--out', path.join(root, 'deliverables/atlas-production/final')));

const EXCLUDED_DIRS = new Set(['node_modules', 'dist', '.git', '.temp', 'work', 'backups', 'backups-remote', 'deliverables']);
const isExcluded = (rel) => rel.split('/').some((p) => EXCLUDED_DIRS.has(p));
const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

async function walk(dir, base = dir) {
  const out = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    const rel = path.relative(base, abs).split(path.sep).join('/');
    if (isExcluded(rel) || entry.isSymbolicLink()) continue;
    if (entry.isDirectory()) out.push(...(await walk(abs, base)));
    else if (entry.isFile()) out.push({ rel, abs });
  }
  return out;
}

const files = (await walk(root)).sort((a, b) => a.rel.localeCompare(b.rel));
const current = new Map();
let totalBytes = 0;
for (const f of files) {
  const bytes = await fs.readFile(f.abs);
  totalBytes += bytes.length;
  current.set(f.rel, { size: bytes.length, sha256: sha256(bytes) });
}

const baseline = JSON.parse(await fs.readFile(baselinePath, 'utf8'));
const baseMap = new Map(baseline.files.map((f) => [f.path, f]));

const added = [];
const modified = [];
const removed = [];
const unchanged = [];
for (const [rel, cur] of current) {
  const base = baseMap.get(rel);
  if (!base) added.push({ path: rel, ...cur });
  else if (base.sha256 !== cur.sha256 || base.size !== cur.size) {
    modified.push({ path: rel, baselineSha256: base.sha256, finalSha256: cur.sha256, baselineSize: base.size, finalSize: cur.size });
  } else unchanged.push({ path: rel, ...cur });
}
for (const [rel, base] of baseMap) if (!current.has(rel)) removed.push({ path: rel, sha256: base.sha256, size: base.size });

await fs.mkdir(outDir, { recursive: true });

const finalManifest = {
  label: 'FINAL',
  generatedAt: new Date().toISOString(),
  workspace: root,
  notAGitRepository: true,
  algorithm: 'sha256',
  excludedDirectories: [...EXCLUDED_DIRS].sort(),
  baselineManifest: path.relative(root, baselinePath).split(path.sep).join('/'),
  baselineGeneratedAt: baseline.generatedAt,
  fileCount: current.size,
  totalBytes,
  combinedTreeSha256: sha256(Buffer.from([...current].map(([p, v]) => `${p} ${v.sha256}`).join('\n'))),
  files: [...current].map(([p, v]) => ({ path: p, size: v.size, sha256: v.sha256 })),
};
await fs.writeFile(path.join(outDir, 'FINAL_HASHES.json'), JSON.stringify(finalManifest, null, 2) + '\n');
await fs.writeFile(path.join(outDir, 'FINAL_FILE_TREE.txt'), [...current.keys()].join('\n') + '\n');
await fs.writeFile(
  path.join(outDir, 'FINAL_TIMESTAMP.txt'),
  `label=FINAL\ngeneratedAt=${finalManifest.generatedAt}\nbaselineGeneratedAt=${baseline.generatedAt}\nfileCount=${finalManifest.fileCount}\ntotalBytes=${totalBytes}\ncombinedTreeSha256=${finalManifest.combinedTreeSha256}\n`,
);

const rows = (list) => list.map((x) => `| \`${x.path}\` | ${x.size ?? x.finalSize} | ${(x.sha256 ?? x.finalSha256).slice(0, 16)}… |`).join('\n');
const md = `# FILE_CHANGE_REPORT — Atlas production takeover

Workspace: \`${root}\`
**Workspace is not a Git repository.** This report is the hash-manifest substitute for a diff,
generated by comparing \`BASELINE_HASHES.json\` with a freshly recomputed final manifest.

| | |
|---|---|
| Baseline generated | ${baseline.generatedAt} |
| Final generated | ${finalManifest.generatedAt} |
| Baseline files | ${baseline.fileCount} |
| Final files | ${finalManifest.fileCount} |
| Added | ${added.length} |
| Modified | ${modified.length} |
| Removed | ${removed.length} |
| Unchanged | ${unchanged.length} |

Excluded from both manifests (non-source, transient or evidence output):
${[...EXCLUDED_DIRS].sort().map((d) => `\`${d}\``).join(', ')}

## ADDED (${added.length})

| Path | Size | SHA-256 |
|---|---|---|
${rows(added) || '| _(none)_ | | |'}

## MODIFIED (${modified.length})

| Path | Baseline → Final SHA-256 | Size |
|---|---|---|
${modified.map((x) => `| \`${x.path}\` | \`${x.baselineSha256.slice(0, 16)}…\` → \`${x.finalSha256.slice(0, 16)}…\` | ${x.baselineSize} → ${x.finalSize} |`).join('\n') || '| _(none)_ | | |'}

## REMOVED (${removed.length})

| Path | Size | SHA-256 |
|---|---|---|
${rows(removed) || '| _(none)_ | | |'}

## UNCHANGED (${unchanged.length})

${unchanged.length} files are byte-identical to the baseline manifest.

## Verification

- Recompute any entry with: \`node -e "const c=require('crypto'),f=require('fs');console.log(c.createHash('sha256').update(f.readFileSync('<path>')).digest('hex'))"\`
- \`combinedTreeSha256\` binds each path to its content hash: a path rename or content edit changes it.
`;
await fs.writeFile(path.join(outDir, 'FILE_CHANGE_REPORT.md'), md);

console.log(JSON.stringify({
  baseline: path.relative(root, baselinePath).split(path.sep).join('/'),
  outDir: path.relative(root, outDir).split(path.sep).join('/'),
  baselineFiles: baseline.fileCount,
  finalFiles: finalManifest.fileCount,
  added: added.length,
  modified: modified.length,
  removed: removed.length,
  unchanged: unchanged.length,
  combinedTreeSha256: finalManifest.combinedTreeSha256,
  addedPaths: added.map((x) => x.path),
  modifiedPaths: modified.map((x) => x.path),
  removedPaths: removed.map((x) => x.path),
}, null, 2));
